/**
 *****************************************************************************************
 *
 * @file sensor_status_manager.h
 *
 * @brief 传感器状态管理器 - 简化传感器状态为正常/异常两种状态
 *
 * @details 功能概述：
 *          - 将ES100传感器的复杂状态码简化为正常(0)/异常(1)两种状态
 *          - 提供状态查询和更新接口
 *          - 支持超级指令获取状态信息
 *
 *****************************************************************************************
 */

#ifndef __SENSOR_STATUS_MANAGER_H__
#define __SENSOR_STATUS_MANAGER_H__

#include <stdint.h>
#include <stdbool.h>
#include "sensor_data_parser.h"

/*
 * DEFINES
 *****************************************************************************************
 */
#define SENSOR_STATUS_NORMAL    0   /**< 传感器状态正常 */
#define SENSOR_STATUS_ABNORMAL  1   /**< 传感器状态异常 */

/*
 * ENUMERATIONS
 *****************************************************************************************
 */
/**@brief 简化的传感器状态枚举. */
typedef enum
{
    SENSOR_SIMPLE_STATUS_NORMAL = 0,    /**< 正常状态 */
    SENSOR_SIMPLE_STATUS_ABNORMAL = 1,  /**< 异常状态 */
} sensor_simple_status_t;

/*
 * STRUCTURES
 *****************************************************************************************
 */
/**@brief 传感器状态信息结构体. */
typedef struct
{
    sensor_simple_status_t current_status;  /**< 当前简化状态 */
    uint8_t raw_status_code;                /**< 原始状态码 */
    uint32_t last_update_time;              /**< 最后更新时间戳 */
    bool status_valid;                      /**< 状态有效标志 */
} sensor_status_info_t;

/*
 * FUNCTION DECLARATIONS
 *****************************************************************************************
 */

/**
 *****************************************************************************************
 * @brief 初始化传感器状态管理器
 *****************************************************************************************
 */
void sensor_status_manager_init(void);

/**
 *****************************************************************************************
 * @brief 根据原始状态码更新简化状态
 *
 * @param[in] raw_status_code: ES100原始状态码
 *****************************************************************************************
 */
void sensor_status_update(uint8_t raw_status_code);

/**
 *****************************************************************************************
 * @brief 获取当前简化状态
 *
 * @return 当前简化状态 (0=正常, 1=异常)
 *****************************************************************************************
 */
sensor_simple_status_t sensor_status_get_simple(void);

/**
 *****************************************************************************************
 * @brief 获取完整的传感器状态信息
 *
 * @param[out] p_status_info: 指向状态信息结构体的指针
 *
 * @return true 如果状态信息有效, false 否则
 *****************************************************************************************
 */
bool sensor_status_get_info(sensor_status_info_t *p_status_info);

/**
 *****************************************************************************************
 * @brief 检查传感器状态是否正常
 *
 * @return true 如果传感器正常, false 如果异常或状态无效
 *****************************************************************************************
 */
bool sensor_status_is_normal(void);

/**
 *****************************************************************************************
 * @brief 根据ES100状态码判断是否为正常状态
 *
 * @param[in] status_code: ES100状态码
 *
 * @return true 如果状态码表示正常, false 否则
 *****************************************************************************************
 */
bool sensor_status_is_code_normal(uint8_t status_code);

/**
 *****************************************************************************************
 * @brief 获取状态码的文本描述
 *
 * @param[in] status_code: ES100状态码
 *
 * @return 状态码的文本描述字符串
 *****************************************************************************************
 */
const char* sensor_status_get_description(uint8_t status_code);

#endif /* __SENSOR_STATUS_MANAGER_H__ */ 
